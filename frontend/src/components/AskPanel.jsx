import { useState } from "react";
import { ArrowUp, Loader2, Sparkles } from "lucide-react";

export const EXAMPLE_QUESTIONS = [
  "What is the total revenue?",
  "Which product generated the highest revenue?",
  "Show monthly revenue trends.",
  "Which region generated the highest sales?",
  "Compare January and February 2026.",
];

const MAX_LENGTH = 500;

export default function AskPanel({ onAsk, loading, examples = EXAMPLE_QUESTIONS, autoFocus = false }) {
  const [question, setQuestion] = useState("");

  const submit = (text) => {
    const q = (text ?? question).trim();
    if (!q || loading) return;
    setQuestion(q);
    onAsk(q);
  };

  return (
    <section className="card ask" aria-label="Ask a question">
      <div className="ask__head">
        <span className="ask__icon" aria-hidden="true">
          <Sparkles size={16} />
        </span>
        <div>
          <h2>Ask about your sales</h2>
          <p>Answers are computed from the SQLite database — never generated by the AI.</p>
        </div>
      </div>
      <form
        className="ask__form"
        onSubmit={(e) => {
          e.preventDefault();
          submit();
        }}
      >
        <label htmlFor="question" className="sr-only">
          Your question
        </label>
        <textarea
          id="question"
          rows={1}
          value={question}
          maxLength={MAX_LENGTH}
          autoFocus={autoFocus}
          placeholder="e.g. How did revenue change between March and April?"
          onChange={(e) => setQuestion(e.target.value)}
          onKeyDown={(e) => {
            // Enter submits; Shift+Enter inserts a newline.
            if (e.key === "Enter" && !e.shiftKey && !e.nativeEvent.isComposing) {
              e.preventDefault();
              submit();
            }
          }}
        />
        <button className="btn btn--primary ask__submit" type="submit" disabled={loading || !question.trim()}>
          {loading ? <Loader2 size={16} className="spin" aria-hidden="true" /> : <ArrowUp size={16} aria-hidden="true" />}
          <span>{loading ? "Analysing" : "Ask"}</span>
        </button>
      </form>
      <div className="ask__examples" aria-label="Example questions">
        {examples.map((q) => (
          <button key={q} type="button" className="chip" disabled={loading} onClick={() => submit(q)}>
            {q}
          </button>
        ))}
      </div>
    </section>
  );
}
